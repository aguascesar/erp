/**
 * Obtiene el catálogo completo de productos
 * @returns {Array} Array de productos con id y nombre
 */
function obtenerProductosCatalogo() {
  return productosCatalogo;
}

/**
 * Obtiene el catálogo completo de clientes
 * @returns {Array} Array de clientes con id, rut y razón social
 */
function obtenerClientesCatalogo() {
  return clientesCatalogo;
}

/**
 * Busca un producto por ID
 * @param {number} id - ID del producto
 * @returns {Object|null} Producto encontrado o null
 */
function buscarProductoPorId(id) {
  return productosCatalogo.find(p => p.id === id) || null;
}

/**
 * Busca un producto por nombre
 * @param {string} nombre - Nombre del producto
 * @returns {Object|null} Producto encontrado o null
 */
function buscarProductoPorNombre(nombre) {
  return productosCatalogo.find(p => 
    p.nombre.toLowerCase().includes(nombre.toLowerCase())
  ) || null;
}

/**
 * Busca un cliente por ID
 * @param {number} id - ID del cliente
 * @returns {Object|null} Cliente encontrado o null
 */
function buscarClientePorId(id) {
  return clientesCatalogo.find(c => c.id === id) || null;
}

/**
 * Busca un cliente por RUT
 * @param {string} rut - RUT del cliente
 * @returns {Object|null} Cliente encontrado o null
 */
function buscarClientePorRut(rut) {
  return clientesCatalogo.find(c => c.rut === rut) || null;
}

/**
 * Busca un cliente por razón social
 * @param {string} rSocial - Razón social del cliente
 * @returns {Object|null} Cliente encontrado o null
 */
function buscarClientePorRazonSocial(rSocial) {
  return clientesCatalogo.find(c => 
    c.rSocial.toLowerCase().includes(rSocial.toLowerCase())
  ) || null;
}

/**
 * Filtra productos por término de búsqueda
 * @param {string} termino - Término de búsqueda
 * @returns {Array} Array de productos que coinciden
 */
function filtrarProductos(termino) {
  if (!termino) return productosCatalogo;
  const term = termino.toLowerCase();
  return productosCatalogo.filter(p => 
    p.nombre.toLowerCase().includes(term)
  );
}

/**
 * Filtra clientes por término de búsqueda
 * @param {string} termino - Término de búsqueda
 * @returns {Array} Array de clientes que coinciden
 */
function filtrarClientes(termino) {
  if (!termino) return clientesCatalogo;
  const term = termino.toLowerCase();
  return clientesCatalogo.filter(c => 
    c.rSocial.toLowerCase().includes(term) || 
    c.rut.toLowerCase().includes(term)
  );
}
